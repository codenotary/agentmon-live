test('a project exception with a reason silences its file; one without a reason does not', async ($, on) => {
  const clock = mock.clock(on)
  engine(on, { '/repo/src/schema.ts': 19 * KB, '/repo/src/legacy.ts': 19 * KB }, { '/repo/src/schema.ts': 40 * KB, '/repo/src/legacy.ts': 40 * KB }, 'src/schema.ts  # one table per type, kept together\nsrc/legacy.ts\n')
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })
  await clock.settle()
  await $.tool.call({ tool: 'Write', file_path: '/repo/src/schema.ts', content: '' })
  await $.tool.call({ tool: 'Write', file_path: '/repo/src/legacy.ts', content: '' })
  await clock.settle()
  const ui = await $.ui.mount(PANE)
  expect(await focusRows(ui)).toEqual([expect.stringContaining('src/legacy.ts')])
  await ui.unmount()
})

