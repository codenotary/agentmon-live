import type { TestBody } from 'claude-code/testing'
import { expect, mock, test } from 'claude-code/testing'

import { globToRegExp, parseExceptions, relPath } from '../hooks/sizeguard'

type On = Parameters<TestBody>[1]

const PANE = {
  plugin: 'agentmon-live',
  component: 'Pane',
  requestId: 'agentmon-live',
  surface: 'terminal',
  props: { title: 'AgentMon Live', isFocused: false, bodyColumns: 120, placement: 'dock', scroll: { offset: 0, bodyRows: 80 }, view: {} },
} as const

const KB = 1000

// A project at /repo whose files have the sizes in `sizes`; an edit sets the size in `after`, even one that reports failure.
function engine(on: On, sizes: Record<string, number>, after: Record<string, number>, exceptions?: string, fails = false) {
  on('command.register', () => ({ value: { command: 'agentmon' } }))
  on('ui.open', () => ({ value: { isPlaced: true } }))
  on('session.model', () => ({ value: 'claude-opus-5-5' }))
  on('session.usage', () => ({ value: { startedAt: 0, context: { window: 1000000, tokens: 10000, percent: 1 }, rateLimits: [] } }))
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  on('ui.status', () => ({ value: undefined }))
  on('prompt.read', () => ({ value: { text: '', cursor: 0 } }))
  on('fs.read', (_, e) => {
    if (exceptions !== undefined && e.path === '/repo/.agentmon-size') return { value: exceptions }
    throw new Error('ENOENT')
  })
  on('fs.stat', (_, e) => {
    const size = sizes[e.path]
    if (size === undefined) throw new Error('ENOENT')
    return { value: { kind: 'file' as const, size, mtimeMs: 0, isLink: false } }
  })
  on('tool.call', (_, e) => {
    const path = (e as { file_path?: string }).file_path
    if (path && after[path] !== undefined) sizes[path] = after[path]!
    return fails ? { result: {}, text: 'old_string not found', isError: true } : { result: {} }
  })
}

const focusRows = async (ui: { findAll: (q: { type: 'Text'; text: RegExp }) => Promise<{ text: string }[]> }) =>
  (await ui.findAll({ type: 'Text', text: /over the 20\.0 KB guide/ })).map(x => x.text)

test('globs match whole relative paths, with ** for any directories', () => {
  expect(globToRegExp('**/dist/**').test('dist/a.js')).toBe(true)
  expect(globToRegExp('**/dist/**').test('pkg/dist/a.js')).toBe(true)
  expect(globToRegExp('**/dist/**').test('distance.ts')).toBe(false)
  expect(globToRegExp('**/*.min.*').test('web/app.min.js')).toBe(true)
  expect(globToRegExp('src/big file.ts').test('src/big file.ts')).toBe(true)
  expect(globToRegExp('src/*.ts').test('src/a/b.ts')).toBe(false)
  expect(relPath('/repo/src/a.ts', '/repo')).toBe('src/a.ts')
  expect(relPath('/elsewhere/a.ts', '/repo')).toBe(undefined)
})

test('an exception needs a reason', () => {
  expect(parseExceptions('# comment\nsrc/schema.ts  # generated by hand from the spec\nsrc/legacy.ts\n\nlib/*.ts #ported, split later')).toEqual(['src/schema.ts', 'lib/*.ts'])
})

test('a hostile glob is dropped or tamed, never left to backtrack', () => {
  expect(parseExceptions('*a*a*a*a*a.ts  # too many wildcards')).toEqual([])
  const started = Date.now()
  expect(globToRegExp('************************z').test('src/components/AppHeader.ts')).toBe(false)
  expect(Date.now() - started).toBeLessThan(100)
})

test('a file that grows past the guide shows in Focus with advice on splitting', async ($, on) => {
  const clock = mock.clock(on)
  const filled: string[] = []
  engine(on, { '/repo/src/api.ts': 19 * KB }, { '/repo/src/api.ts': 21 * KB })
  on('prompt.fill', (_, e) => {
    filled.push(e.text)
    return { isFilled: true }
  })
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })
  await $.tool.call({ tool: 'Edit', file_path: '/repo/src/api.ts', old_string: 'a', new_string: 'b' })
  await clock.settle()
  const ui = await $.ui.mount(PANE)
  expect(await focusRows(ui)).toEqual([expect.stringContaining('src/api.ts 21.0 KB · over the 20.0 KB guide (≈5k tokens)')])
  await ui.press({ key: 'investigate:0' })
  expect(filled.at(-1)).toContain('/repo/src/api.ts is 21.0 KB, past the 20000-byte guide')
  expect(filled.at(-1)).toContain('a size heuristic, not a token count')
  expect(filled.at(-1)).toContain('Do not split it arbitrarily or add abstractions')
  await ui.unmount()
})

test('an oversized file that does not grow, excluded files and a failed edit stay quiet', async ($, on) => {
  const clock = mock.clock(on)
  const sizes = { '/repo/src/old.ts': 30 * KB, '/repo/dist/x.js': 10 * KB, '/repo/package-lock.json': 10 * KB, '/repo/web/a.min.js': 10 * KB, '/repo/docs/a.md': 10 * KB }
  engine(on, sizes, { '/repo/src/old.ts': 29 * KB, '/repo/dist/x.js': 90 * KB, '/repo/package-lock.json': 90 * KB, '/repo/web/a.min.js': 90 * KB, '/repo/docs/a.md': 90 * KB })
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })
  for (const file_path of Object.keys(sizes)) await $.tool.call({ tool: 'Write', file_path, content: '' })
  await clock.settle()
  const ui = await $.ui.mount(PANE)
  expect(await focusRows(ui)).toEqual([])
  await ui.unmount()
})

test('a new oversized file shows, from a subagent too', async ($, on) => {
  const clock = mock.clock(on)
  engine(on, {}, { '/repo/src/new.ts': 25 * KB })
  on('agent.spawn', () => ({ model: 'claude-haiku-5-5', agentId: 'a1' }))
  await $.session.start({ cwd: '/repo', surface: 'terminal', isInteractive: true })
  await $.agent.spawn({ prompt: 'p', description: 'd', subagentType: 'Explore', tool_use_id: 't1' } as never)
  await $.tool.call({ tool: 'Write', file_path: '/repo/src/new.ts', content: 'x', agentId: 'a1' })
  await clock.settle()
  const ui = await $.ui.mount(PANE)
  expect(await focusRows(ui)).toEqual([expect.stringContaining('src/new.ts 25.0 KB')])
  await ui.unmount()
})

